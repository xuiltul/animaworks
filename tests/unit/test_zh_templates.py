"""Unit tests for Japanese and Simplified Chinese locale template parity.

``templates/zh/`` is generated by ``scripts/translate.py templates --lang zh``.
Until that batch translation has been run, these tests fail with explicit
"Missing zh template" messages instead of being skipped.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

_TEMPLATES_DIR = Path(__file__).resolve().parents[2] / "templates"
_JA_DIR = _TEMPLATES_DIR / "ja"
_ZH_DIR = _TEMPLATES_DIR / "zh"


def _ja_files() -> list[str]:
    return sorted(path.relative_to(_JA_DIR).as_posix() for path in _JA_DIR.rglob("*") if path.is_file())


def _markdown_files() -> list[str]:
    return [path for path in _ja_files() if path.endswith(".md")]


def _read_zh(rel_path: str) -> str:
    path = _ZH_DIR / rel_path
    assert path.is_file(), f"Missing zh template: {rel_path}"
    return path.read_text(encoding="utf-8")


_PLACEHOLDER_RE = re.compile(r"(?<!\{)\{([A-Za-z_][A-Za-z0-9_.]*)\}(?!\})")


def _strip_code_blocks(text: str) -> str:
    """Remove fenced code blocks, where placeholders are illustrative text."""
    return re.sub(r"```.*?```|~~~.*?~~~", "", text, flags=re.DOTALL)


def _extract_placeholders(text: str) -> set[str]:
    return set(_PLACEHOLDER_RE.findall(_strip_code_blocks(text)))


class TestZhTemplateFilesExist:
    """Every Japanese source file must have exactly one Chinese counterpart."""

    @pytest.mark.parametrize("rel_path", _ja_files())
    def test_expected_file_exists(self, rel_path: str) -> None:
        assert (_ZH_DIR / rel_path).is_file(), f"Missing zh template: {rel_path}"

    def test_locale_file_sets_match_ja(self) -> None:
        ja_files = set(_ja_files())
        zh_files = {path.relative_to(_ZH_DIR).as_posix() for path in _ZH_DIR.rglob("*") if path.is_file()}
        assert zh_files == ja_files, (
            f"zh file set differs from ja. Extra: {zh_files - ja_files}; missing: {ja_files - zh_files}"
        )


