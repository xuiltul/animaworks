@pytest.mark.parametrize(
    "rel_path",
    [
        path
        for path in _markdown_files()
        if path not in _HEADING_EXEMPT and not path.startswith("prompts/tool_descriptions/")
    ],
)
def test_zh_markdown_has_heading(rel_path: str) -> None:
    heading_prefixes = ("## ", "### ", "#### ", "##### ", "###### ")
    ja_text = (_JA_DIR / rel_path).read_text(encoding="utf-8")
    if not any(line.startswith(heading_prefixes) for line in ja_text.splitlines()):
        pytest.skip("ja source has no ## headings")
    text = _read_zh(rel_path)
    assert any(line.startswith(heading_prefixes) for line in text.splitlines()), (
        f"{rel_path} has no ## or deeper headings"
    )


@pytest.mark.parametrize("rel_path", _markdown_files())
def test_placeholders_match_ja(rel_path: str) -> None:
    ja_placeholders = _extract_placeholders((_JA_DIR / rel_path).read_text(encoding="utf-8"))
    zh_placeholders = _extract_placeholders(_read_zh(rel_path))
    assert zh_placeholders == ja_placeholders, (
        f"{rel_path}: zh placeholders differ from ja; missing={ja_placeholders - zh_placeholders}, "
        f"extra={zh_placeholders - ja_placeholders}"
    )


def test_zh_copy_files_are_byte_identical_to_ja() -> None:
    """Non-Markdown template files are copied verbatim by the pipeline."""
    for rel_path in _ja_files():
        if rel_path.endswith(".md"):
            continue
        path = _ZH_DIR / rel_path
        assert path.is_file(), f"Missing zh template: {rel_path}"
        assert path.read_bytes() == (_JA_DIR / rel_path).read_bytes(), f"{rel_path}: byte copy differs from ja"
